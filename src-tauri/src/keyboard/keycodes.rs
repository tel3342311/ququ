#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[cfg(target_os = "macos")]
    fn key_to_vk_maps_common_macos_keys() {
        assert_eq!(key_to_vk(&Code::KeyA), Some(0x00));
        assert_eq!(key_to_vk(&Code::Space), Some(0x31));
        assert_eq!(key_to_vk(&Code::Enter), Some(0x24));
        assert_eq!(key_to_vk(&Code::F2), Some(0x78));
        assert_eq!(key_to_vk(&Code::Escape), Some(0x35));
    }

    #[test]
    #[cfg(windows)]
    fn key_to_vk_maps_common_windows_keys() {
        assert_eq!(key_to_vk(&Code::KeyA), Some(0x41));
        assert_eq!(key_to_vk(&Code::Space), Some(0x20));
        assert_eq!(key_to_vk(&Code::F2), Some(0x71));
    }
}
